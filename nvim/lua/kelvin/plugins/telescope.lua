require("telescope").setup({})
local b = require("telescope.builtin")

vim.keymap.set("n", "<leader>pf", b.find_files, { desc = "Tìm file" })
vim.keymap.set("n", "<C-p>", b.git_files, { desc = "Tìm file trong git" })
vim.keymap.set("n", "<leader>pws", function()
    b.grep_string({ search = vim.fn.expand("<cword>") })
end, { desc = "Grep từ dưới con trỏ" })
vim.keymap.set("n", "<leader>pWs", function()
    b.grep_string({ search = vim.fn.expand("<cWORD>") })
end, { desc = "Grep WORD dưới con trỏ" })
vim.keymap.set("n", "<leader>ps", b.live_grep, { desc = "Live grep" })
vim.keymap.set("n", "<leader>vh", b.help_tags, { desc = "Help tags" })
vim.keymap.set("n", "<leader>pb", b.buffers, { desc = "Buffers" })
